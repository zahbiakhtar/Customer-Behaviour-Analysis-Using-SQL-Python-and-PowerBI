-- 11. Are customers who are repeat buyer(more than 5 previous purchases) also likely to subscribe?

SELECT * FROM customer_behaviour_analysis;

SELECT
    CASE
        WHEN previous_purchases > 5 THEN 'Repeat Buyers'
        ELSE 'Normal Buyers'
    END AS customer_type,

    subscription_status,

    COUNT(*) AS customer_count,

    COUNT(*) * 100.0 /
    SUM(COUNT(*)) OVER (
        PARTITION BY
            CASE
                WHEN previous_purchases > 5 THEN 'Repeat Buyers'
                ELSE 'Normal Buyers'
            END
    ) AS percents

FROM customer_behaviour_analysis

GROUP BY
    CASE
        WHEN previous_purchases > 5 THEN 'Repeat Buyers'
        ELSE 'Normal Buyers'
    END,
    subscription_status;
    
