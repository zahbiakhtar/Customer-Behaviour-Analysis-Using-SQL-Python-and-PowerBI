SELECT * FROM customer_behaviour_analysis;

WITH CTE AS (
    SELECT
        category,
        item_purchased,

        COUNT(item_purchased) AS most_purchased,

        RANK() OVER (
            PARTITION BY category
            ORDER BY COUNT(item_purchased) DESC
        ) AS RNK

    FROM customer_behaviour_analysis

    GROUP BY
        category,
        item_purchased
)

SELECT *
FROM CTE
WHERE RNK <= 3;

